export type GateEntryDirection = 'in' | 'out' | 'return';
export type GateVehicleMode = 'vehicle' | 'non_vehicle';

export interface GateEntryTypeConfig {
  id: string;
  title: string;
  description: string;
  direction: GateEntryDirection;
  vehicleMode: GateVehicleMode;
  dashboardRoute: string;
  newEntryRoute: string;
  viewPermissions: readonly string[];
  createPermissions: readonly string[];
  icon: LucideIcon;
  colorClassName: string;
  keywords: readonly string[];
  requiresWeighment?: boolean;
  requiresGatepass?: boolean;
  /**
   * Hide from the "New Entry" picker. For flows the gate acts on but does not
   * originate — a returnable gate pass is raised by a department, and the gate
   * only works its queue.
   */
  hideFromNewEntry?: boolean;
}

