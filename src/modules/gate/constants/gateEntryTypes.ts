export const GATE_ENTRY_CREATE_PERMISSIONS = Array.from(
  new Set(GATE_ENTRY_TYPES.flatMap((entryType) => entryType.createPermissions)),
);

export const GATE_ENTRY_VIEW_PERMISSIONS = Array.from(
  new Set(GATE_ENTRY_TYPES.flatMap((entryType) => entryType.viewPermissions)),
);

export function findGateEntryType(entryTypeId: string | undefined) {
  return GATE_ENTRY_TYPES.find((entryType) => entryType.id === entryTypeId);
}
